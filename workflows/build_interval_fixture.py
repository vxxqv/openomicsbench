"""Build the deterministic chromatin peak benchmark introduced in version 6."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from omicsbench.hashing import digest
from omicsbench.intervals import summarize_intervals


PEAKS = [
    ("chrSynthetic1", 500, 700), ("chrSynthetic1", 1400, 1650), ("chrSynthetic1", 2500, 3300),
    ("chrSynthetic1", 4100, 4300), ("chrSynthetic1", 4380, 4600), ("chrSynthetic1", 6000, 6250),
    ("chrSynthetic1", 8200, 8450), ("chrSynthetic1", 10500, 10800), ("chrSynthetic2", 300, 550),
    ("chrSynthetic2", 1800, 2050), ("chrSynthetic2", 3900, 4300), ("chrSynthetic2", 6900, 7200),
]
SIZES = {"chrSynthetic1": 12000, "chrSynthetic2": 8000}


def write_text(path: Path, value: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8", newline="\n")


def record(folder: Path, path: str, tier: str, role: str, media: str) -> dict:
    absolute = folder / path
    return {"path": path, "tier": tier, "role": role, "media_type": media, "bytes": absolute.stat().st_size, "sha256": digest(absolute)}


def build(destination: Path) -> Path:
    folder = destination / "datasets" / "intervals" / "interval-001"
    write_text(folder / "nano/chrom.sizes", "".join(f"{chrom}\t{size}\n" for chrom, size in SIZES.items()))
    rows = []
    for index, (chrom, start, end) in enumerate(PEAKS, 1):
        width = end - start
        signal = 20 + index
        rows.append(f"{chrom}\t{start}\t{end}\tpeak-{index:02d}\t{min(1000, signal * 20)}\t.\t{signal}.0\t10.0\t8.0\t{width // 2}")
    write_text(folder / "expected/truth-peaks.narrowPeak", "\n".join(rows) + "\n")
    signal_rows = []
    for chrom, size in SIZES.items():
        for start in range(0, size, 50):
            end = min(size, start + 50)
            midpoint = (start + end) // 2
            covering = [peak for peak in PEAKS if peak[0] == chrom and peak[1] <= midpoint < peak[2]]
            value = 2 + ((start // 50) % 3)
            if covering:
                peak = covering[0]
                centre = (peak[1] + peak[2]) / 2
                value += round(28 * (1 - abs(midpoint - centre) / ((peak[2] - peak[1]) / 2 + 50)), 3)
            signal_rows.append(f"{chrom}\t{start}\t{end}\t{value}")
    write_text(folder / "nano/coverage.bedgraph", "\n".join(signal_rows) + "\n")
    summary = summarize_intervals(folder / "expected/truth-peaks.narrowPeak", folder / "nano/chrom.sizes")
    profile = {
        "profile": "synthetic-peak-recovery-v1",
        "signal": "nano/coverage.bedgraph",
        "chrom_sizes": "nano/chrom.sizes",
        "interval_truth": "expected/truth-peaks.narrowPeak",
        "expected_summary": summary,
        "peak_comparison": {
            "minimum_interval_precision": 0.9, "minimum_interval_recall": 0.9, "minimum_interval_f1": 0.9,
            "minimum_base_precision": 0.85, "minimum_base_recall": 0.85, "minimum_base_f1": 0.85,
        },
    }
    write_text(folder / "expected/validation.json", json.dumps(profile, indent=2) + "\n")
    files = [
        record(folder, "nano/coverage.bedgraph", "nano", "signal", "text/plain"),
        record(folder, "nano/chrom.sizes", "nano", "chrom_sizes", "text/plain"),
        record(folder, "expected/truth-peaks.narrowPeak", "expected", "intervals", "text/plain"),
        record(folder, "expected/validation.json", "expected", "metrics", "application/json"),
    ]
    manifest = {
        "schema_version": "4.0", "id": "interval-001", "title": "Synthetic chromatin peak-calling benchmark", "release": "6.0.0",
        "assay": "chromatin_accessibility", "kind": "synthetic_fixture", "status": "validated",
        "archetype": "narrow, broad, close-doublet and chromosome-edge peaks over deterministic coverage",
        "organism": "Synthetic genome model", "taxon_id": None,
        "source": {"repository": "Project generator", "accession": "interval-001", "url": "https://github.com/vxxqv/openomicsbench", "citation": "OpenOmicsBench interval-001, project-authored deterministic chromatin peak fixture.", "retrieved": "2026-10-25", "sha256": None},
        "rights": {"status": "GREEN", "license": "Apache-2.0", "evidence": "Generated by the project workflow without third-party reads, signal tracks or intervals.", "checked": "2026-10-25"},
        "reference": {"genome": "synthetic two-contig reference", "annotation": "not_applicable", "namespace": "project synthetic chromosome identifiers", "compatibility": "verified"},
        "samples": [{"sample_id": "synthetic-chromatin-1", "condition": "deterministic accessibility signal", "replicate": 1, "batch": "single synthetic batch", "strandedness": "not_applicable"}],
        "derivation": {"workflow": "workflows/build_interval_fixture.py", "commit": None, "seed": 0, "algorithm": "closed-form deterministic peak and coverage generator", "parameters": {"contigs": 2, "peaks": len(PEAKS), "bin_width": 50}, "versions": {"python": "3.12", "openomicsbench_contract": "4.0"}},
        "files": files, "validation": {"profile": "expected/validation.json", "baseline_version": "genomic-interval-comparison-v1", "metrics": []},
        "sequence": None, "single_cell": None,
        "intervals": {"format": "narrowPeak", "coordinate_system": "zero_based_half_open", "reciprocal_overlap": 0.5},
        "limitations": ["The signal and intervals are synthetic and do not model a specific organism, cell type or chromatin assay.", "The benchmark tests file handling and peak overlap recovery; read alignment, duplicate handling, blacklist filtering, replicate concordance and biological interpretation remain outside its scope."],
    }
    write_text(folder / "manifest.json", json.dumps(manifest, indent=2) + "\n")
    return folder


if __name__ == "__main__":
    target = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT
    print(f"Built {build(target)}")
